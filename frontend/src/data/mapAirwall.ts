/**
 * 判断一个点 (x, y) 是否在多边形内部（Ray-Casting 射线法）
 */
export function isPointInPolygon(point: { x: number; y: number }, polygon = AIRWALL_POLYGON_L13): boolean {
  let inside = false;
  const n = polygon.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const xi = polygon[i][0];
    const yi = polygon[i][1];
    const xj = polygon[j][0];
    const yj = polygon[j][1];

    const intersect = yi > point.y !== yj > point.y &&
      point.x < ((xj - xi) * (point.y - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

/**
 * 使用闭合二次贝塞尔曲线平滑绘制空气墙边界多边形到 Canvas 上，
 * 呈现自然圆润、精细贴合的岛屿海岸线轮廓。
 */
export function drawSmoothClosedPolygon(
  ctx: CanvasRenderingContext2D,
  points: [number, number][],
  screenOffsetX: number,
  screenOffsetY: number,
  zoom: number
) {
  const n = points.length;
  if (n < 3) return;

  // 将世界坐标转为屏幕坐标
  const screenPts = new Array<{ x: number; y: number }>(n);
  for (let i = 0; i < n; i++) {
    screenPts[i] = {
      x: screenOffsetX + points[i][0] * zoom,
      y: screenOffsetY + points[i][1] * zoom,
    };
  }

  // 闭合样条曲线：计算前一个点与当前点的中点作为曲线起点
  const firstMidX = (screenPts[n - 1].x + screenPts[0].x) / 2;
  const firstMidY = (screenPts[n - 1].y + screenPts[0].y) / 2;

  ctx.beginPath();
  ctx.moveTo(firstMidX, firstMidY);

  for (let i = 0; i < n; i++) {
    const current = screenPts[i];
    const next = screenPts[(i + 1) % n];
    const midX = (current.x + next.x) / 2;
    const midY = (current.y + next.y) / 2;

    // 二次贝塞尔曲线：以顶点为控制点，平滑过渡到相邻两点的中点
    ctx.quadraticCurveTo(current.x, current.y, midX, midY);
  }

  ctx.closePath();
}
